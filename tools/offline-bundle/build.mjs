#!/usr/bin/env node
// Build a self-contained, network-free copy of the Week 1 presenter deck.
//
// Why this exists: the school has no network. The deployed deck at /starx-week-1/
// pulls three typefaces from Google Fonts and eight clip poster frames from
// img.youtube.com, so with the Wi-Fi off it loses its type and shows blank boxes
// on every external-clip screen before anyone presses play.
//
// This script is ADDITIVE. It reads public/starx-week-1/index.html and writes a
// separate bundle. It never writes back into public/.
//
// Usage:  node tools/offline-bundle/build.mjs
// Output: dist-offline/starx-week-1-offline/  (gitignored)

import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, '..', '..');
const SRC_DIR = join(REPO, 'public', 'starx-week-1');
const SRC_HTML = join(SRC_DIR, 'index.html');
const ASSETS = join(HERE, 'assets');
const OUT = join(REPO, 'dist-offline', 'starx-week-1-offline');

// Every external video id the deck references. Kept explicit rather than parsed:
// if the deck gains a ninth clip, this build must fail loudly, not silently ship
// a bundle with one blank box in it.
const YT_IDS = [
  'vFw_04XfV4I', // Paddington in Peru — Studiocanal
  'EQROSyAMuOM', // The Lion King 1994
  'orLMm76lwjY', // Shaun the Sheep — Aardman
  'vdfMLAH1yJQ', // BBC Earth chameleon
  'BfhV3Q4LJPM', // LEGO (optional)
  'ksxbp9yb9BU', // Sesame Street Elmo (optional)
  '7TavVZMewpY', // The Lion King 2019 — game slot 5
  'oACMU-w1RXw', // Wonka — game slot 6
];

const fail = (msg) => { console.error('BUILD FAILED: ' + msg); process.exit(1); };

// ---------------------------------------------------------------- read source
let html = readFileSync(SRC_HTML, 'utf8');
const srcBytes = Buffer.byteLength(html);

// Guard: the source must still be the deck this script knows how to rewrite.
const GOOGLE_FONT_LINKS =
  '<link rel="preconnect" href="https://fonts.googleapis.com">\n' +
  '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n' +
  '<link href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,400;12..96,600;12..96,800&family=DM+Mono:wght@400;500&family=Work+Sans:wght@400;500;600&display=swap" rel="stylesheet">';
if (!html.includes(GOOGLE_FONT_LINKS)) fail('the Google Fonts <link> block in index.html is not what this script expects — re-check the head and update GOOGLE_FONT_LINKS');

const YT_THUMB_FN = "function ytThumb(id){ return 'https://img.youtube.com/vi/'+id+'/hqdefault.jpg'; }";
if (!html.includes(YT_THUMB_FN)) fail('ytThumb() in index.html is not what this script expects');

const IFRAME_LINE = `      lightboxMedia.innerHTML = '<iframe src="'+ytEmbedSrc(c.id, c.start)+'" title="'+c.title+'" allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture" allowfullscreen></iframe>';`;
if (!html.includes(IFRAME_LINE)) fail('the openLightbox() iframe line in index.html is not what this script expects');

// Every external id referenced in the source must be covered by YT_IDS.
const idsInSource = [...html.matchAll(/id:\s*'([A-Za-z0-9_-]{11})'/g)].map((m) => m[1]);
const uncovered = [...new Set(idsInSource)].filter((id) => !YT_IDS.includes(id));
if (uncovered.length) fail('external video id(s) with no downloaded poster frame: ' + uncovered.join(', ') + ' — run tools/offline-bundle/fetch-assets.sh');

// ------------------------------------------------------- 1. embed the fonts
// Each @font-face keeps Google's own font-weight / unicode-range values verbatim,
// so the browser picks exactly the same face for each weight it picks online.
// The woff2 payload is inlined as a data: URI rather than left as a sibling file
// because Chrome and Safari refuse cross-origin font loads under file://, and the
// classroom path is a double-clicked local file.
let fontCss = readFileSync(join(ASSETS, 'fonts.template.css'), 'utf8');
let embedded = 0;
fontCss = fontCss.replace(/FONTFILE:([A-Za-z0-9._-]+)/g, (_, name) => {
  const p = join(ASSETS, 'fonts', name);
  const b64 = readFileSync(p).toString('base64'); // throws if the file is missing
  embedded++;
  return `data:font/woff2;base64,${b64}`;
});
if (embedded !== 16) fail(`expected 16 @font-face payloads, embedded ${embedded}`);

html = html.replace(
  GOOGLE_FONT_LINKS,
  '<!-- OFFLINE BUNDLE: the three typefaces are embedded below as data: URIs.\n' +
  '     Generated by tools/offline-bundle/build.mjs from the same Google Fonts\n' +
  '     stylesheet the online deck links to. Do not hand-edit. -->\n' +
  '<style>\n' + fontCss + '</style>'
);

// -------------------------------------------- 2. local clip poster frames
html = html.replace(
  YT_THUMB_FN,
  "function ytThumb(id){ return 'media/yt-posters/'+id+'.jpg'; } // OFFLINE BUNDLE: local copies of img.youtube.com/vi/<id>/hqdefault.jpg"
);

// ------------------------------- 3. offline-aware fallback for the 8 embeds
// The embeds still stream from YouTube — phase 2 (local clip files) is Eric's
// decision, not ours. So keep the player whenever YouTube can actually be
// reached (the phone-hotspot rung of the day-of ladder), and otherwise show the
// poster frame plus one line of presenter instruction instead of the browser's
// error page.
//
// navigator.onLine is checked but not trusted on its own: a laptop joined to a
// school Wi-Fi that has no uplink reports itself online, which is the likeliest
// shape of "the school network is gone". So the real test is a one-image
// reachability probe against img.youtube.com, cache-busted so a poster left in
// the HTTP cache cannot make a dead network look alive.
const OFFLINE_BRANCH = `      // OFFLINE BUNDLE — see tools/offline-bundle/build.mjs.
      lightboxMedia.innerHTML =
        '<div class="offline-clip">' +
          '<img src="' + ytThumb(c.id) + '" alt="Poster frame for this clip">' +
          '<p class="offline-msg">Loading the clip\\u2026</p>' +
        '</div>';
      var standIn = lightboxMedia.querySelector('.offline-clip');
      var standMsg = standIn.querySelector('.offline-msg');
      var settleClip = function(reachable){
        if (!standIn.isConnected) return; // presenter already pressed Esc
        if (reachable){
${IFRAME_LINE.replace(/^ {6}/, ' '.repeat(10))}
        } else {
          standMsg.innerHTML =
            'This clip streams from YouTube and there is no connection.<br>' +
            'Turn on the phone hotspot, or describe the clip and carry on \\u2014 ' +
            'the answer is on the reveal panel.';
        }
      };
      if (navigator.onLine === false){
        settleClip(false);
      } else {
        var probeDone = false;
        var probeTimer;
        var probeSettle = function(ok){ if (probeDone) return; probeDone = true; clearTimeout(probeTimer); settleClip(ok); };
        probeTimer = setTimeout(function(){ probeSettle(false); }, 3000);
        var probe = new Image();
        probe.onload = function(){ probeSettle(true); };
        probe.onerror = function(){ probeSettle(false); };
        probe.src = 'https://img.youtube.com/vi/' + c.id + '/default.jpg?probe=' + Date.now();
      }`;
html = html.replace(IFRAME_LINE, OFFLINE_BRANCH);

const OFFLINE_CSS = `
  /* OFFLINE BUNDLE only — the stand-in shown while a YouTube clip is being
     reached, and left in place when it cannot be. */
  .offline-clip{position:absolute;inset:0;display:flex;flex-direction:column;align-items:center;justify-content:center;gap:18px;background:var(--ink);padding:24px;text-align:center}
  .offline-clip img{width:min(70%,520px);border-radius:10px;box-shadow:0 14px 34px rgba(0,0,0,.45);opacity:.9}
  .offline-msg{font-family:var(--body);font-size:clamp(13px,1.5vw,17px);line-height:1.55;color:rgba(247,245,239,.92);max-width:46ch;margin:0}
`;
const STYLE_CLOSE = '\n</style>';
const lastStyleClose = html.lastIndexOf(STYLE_CLOSE);
if (lastStyleClose === -1) fail('could not find a closing </style> to append the offline CSS to');
html = html.slice(0, lastStyleClose) + OFFLINE_CSS + html.slice(lastStyleClose);

// ------------------------------------------------------------ 4. write bundle
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

// index.html for anyone serving the folder; START-THE-DECK.html is the one Eric
// double-clicks in Finder. Same bytes — a redirect stub would be one more thing
// that can fail on a cold laptop.
writeFileSync(join(OUT, 'index.html'), html);
writeFileSync(join(OUT, 'START-THE-DECK.html'), html);

cpSync(join(SRC_DIR, 'media'), join(OUT, 'media'), { recursive: true });
cpSync(join(ASSETS, 'yt-posters'), join(OUT, 'media', 'yt-posters'), { recursive: true });

writeFileSync(join(OUT, 'HOW-TO-USE.txt'), readFileSync(join(ASSETS, 'HOW-TO-USE.txt'), 'utf8'));

// ------------------------------------------------------------- 5. self-check
// Two rules, because they fail differently.
//
// (a) Nothing in the static markup may point off-machine. A remote href/src in
//     the markup loads the moment the page opens, which is the blank-box failure
//     this bundle exists to remove.
const markupRemote = [...html.matchAll(/(?:src|href)\s*=\s*"(https?:\/\/[^"]+)"/g)]
  .map((m) => m[1])
  .filter((u) => !u.startsWith('http://www.w3.org/')); // the SVG namespace is a name, not a fetch
if (markupRemote.length) fail('markup still loads from off-machine at idle: ' + markupRemote.join(', '));

// (b) The only remote hosts left anywhere are the two the click path uses:
//     img.youtube.com for the reachability probe, www.youtube.com for the player.
//     Both fire on a click, never at idle. verify.mjs proves that empirically.
const ALLOWED_ON_CLICK = ['www.youtube.com', 'img.youtube.com'];
const hosts = [...new Set([...html.matchAll(/https?:\/\/([^\/"')\s]+)/g)].map((m) => m[1]))]
  .filter((h) => h !== 'www.w3.org');
const unexpected = hosts.filter((h) => !ALLOWED_ON_CLICK.includes(h));
if (unexpected.length) fail('bundle points at unexpected remote host(s): ' + unexpected.join(', '));

let files = 0, bytes = 0;
(function walk(d){ for (const e of readdirSync(d)) { const p = join(d, e); const s = statSync(p); if (s.isDirectory()) walk(p); else { files++; bytes += s.size; } } })(OUT);

console.log('offline bundle written');
console.log('  out          ' + OUT);
console.log('  html         ' + srcBytes.toLocaleString() + ' -> ' + Buffer.byteLength(html).toLocaleString() + ' bytes');
console.log('  fonts        ' + embedded + ' @font-face payloads embedded');
console.log('  posters      ' + YT_IDS.length + ' local clip poster frames');
console.log('  files        ' + files);
console.log('  total        ' + (bytes / 1048576).toFixed(1) + ' MB');
console.log('  idle network  none — youtube is touched only by a click, and only if reachable');
